#!/usr/bin/env tsx
import fs from "node:fs";
import path from "node:path";

export type Feature = {
  id: string;
  title: string;
  aliases: string[];
  routes: string[];
  paths: string[];
  file: string;
};

export type Inspection = {
  features: Feature[];
  routes: string[];
  errors: string[];
  warnings: string[];
  index: string;
};

const MAP_DIR = ".agents/feature-map";
const SOURCE_DIRS = ["components", "hooks", "lib"];

function walk(root: string, relative = ""): string[] {
  const current = path.join(root, relative);
  if (!fs.existsSync(current)) return [];
  return fs.readdirSync(current, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const next = path.posix.join(relative, entry.name);
      if (entry.isDirectory()) return walk(root, next);
      return [next];
    });
}

export function routeFromFile(file: string): string | null {
  if (!/^app\/.*\.(?:ts|tsx|js|jsx)$/.test(file)) return null;
  const withoutApp = file.replace(/^app\//, "").replace(/\.(?:ts|tsx|js|jsx)$/, "");
  const segments = withoutApp.split("/");
  if (segments.some((segment) => segment.startsWith("_"))) return null;
  if (segments.at(-1) === "_layout") return null;
  const publicSegments = segments.filter((segment) => !/^\(.*\)$/.test(segment));
  if (publicSegments.at(-1) === "index") publicSegments.pop();
  return `/${publicSegments.join("/")}`.replace(/\/$/, "") || "/";
}

function parseArray(value: string, field: string, file: string, errors: string[]): string[] {
  try {
    const parsed: unknown = JSON.parse(value);
    if (!Array.isArray(parsed) || parsed.some((item) => typeof item !== "string")) throw new Error();
    return parsed;
  } catch {
    errors.push(`${file}: frontmatter '${field}' must be a JSON-style string array`);
    return [];
  }
}

function validateFields(values: Map<string, string>, file: string, errors: string[]): void {
  const allowed = new Set(["id", "title", "aliases", "routes", "paths"]);
  for (const key of values.keys()) {
    if (!allowed.has(key)) errors.push(`${file}: unknown frontmatter field '${key}'`);
  }
  for (const key of allowed) {
    if (!values.has(key)) errors.push(`${file}: missing frontmatter field '${key}'`);
  }
}

function parseFeature(root: string, file: string, errors: string[]): Feature | null {
  const text = fs.readFileSync(path.join(root, file), "utf8");
  const match = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) {
    errors.push(`${file}: missing YAML frontmatter`);
    return null;
  }
  const values = new Map<string, string>();
  for (const line of match[1].split("\n")) {
    const field = line.match(/^([a-z]+):\s*(.*)$/);
    if (!field) errors.push(`${file}: invalid frontmatter line '${line}'`);
    else values.set(field[1], field[2]);
  }
  validateFields(values, file, errors);
  const id = values.get("id") ?? "";
  const title = values.get("title") ?? "";
  if (!/^[a-z0-9-]+$/.test(id)) errors.push(`${file}: id must use lowercase kebab-case`);
  if (!title.trim()) errors.push(`${file}: title must not be empty`);
  const expectedFile = `${MAP_DIR}/${id}.md`;
  if (id && file !== expectedFile) errors.push(`${file}: id '${id}' must live at ${expectedFile}`);
  return {
    id,
    title,
    aliases: parseArray(values.get("aliases") ?? "", "aliases", file, errors),
    routes: parseArray(values.get("routes") ?? "", "routes", file, errors),
    paths: parseArray(values.get("paths") ?? "", "paths", file, errors),
    file,
  };
}

export function globRegex(glob: string): RegExp {
  let pattern = "^";
  for (let i = 0; i < glob.length; i += 1) {
    const char = glob[i];
    if (char === "*" && glob[i + 1] === "*") {
      pattern += ".*";
      i += 1;
    } else if (char === "*") pattern += "[^/]*";
    else if (char === "?") pattern += "[^/]";
    else pattern += char.replace(/[|\\{}()[\]^$+?.]/g, "\\$&");
  }
  return new RegExp(`${pattern}$`);
}

export function affectedFeatures(features: Feature[], changedFiles: string[]): Feature[] {
  return features.filter((feature) => changedFiles.some((file) => {
    const route = routeFromFile(file);
    return feature.paths.some((pattern) => globRegex(pattern).test(file))
      || (route !== null && feature.routes.includes(route));
  }));
}

function renderIndex(features: Feature[]): string {
  const sorted = [...features].sort((a, b) => a.id.localeCompare(b.id));
  const routeRows = sorted.flatMap((feature) => feature.routes.map((route) => ({ route, feature })))
    .sort((a, b) => a.route.localeCompare(b.route));
  const featureTable = sorted.map((feature) =>
    `| [${feature.id}](./${feature.id}.md) | ${feature.title} | ${feature.aliases.join(", ")} | ${feature.routes.map((route) => `\`${route}\``).join(", ")} |`,
  ).join("\n");
  const routeTable = routeRows.map(({ route, feature }) => `| \`${route}\` | [${feature.title}](./${feature.id}.md) |`).join("\n");
  return `<!-- GENERATED by scripts/feature-map.ts. DO NOT EDIT. -->
# Agent Feature Map

For vague or feature-level work, search aliases below, open the matching feature file, and use its user journey and code entry points before changing code. Update that feature file whenever user-facing behavior, routes, or ownership paths change; run \`npm run feature-map\` afterward.

## Features

| ID | Title | User vocabulary / aliases | Routes |
| --- | --- | --- | --- |
${featureTable}

## Route → feature

| Route | Feature |
| --- | --- |
${routeTable}
`;
}

export function inspectFeatureMap(root: string): Inspection {
  const allFiles = walk(root);
  const errors: string[] = [];
  const featureFiles = allFiles.filter((file) => file.startsWith(`${MAP_DIR}/`) && file.endsWith(".md") && !file.endsWith("/README.md"));
  const features = featureFiles.map((file) => parseFeature(root, file, errors)).filter((item): item is Feature => item !== null);
  const routes = allFiles.map(routeFromFile).filter((route): route is string => route !== null).sort();
  const claimedRoutes = new Map<string, string[]>();
  for (const feature of features) {
    for (const route of feature.routes) claimedRoutes.set(route, [...(claimedRoutes.get(route) ?? []), feature.id]);
    for (const pattern of feature.paths) {
      if (!allFiles.some((file) => globRegex(pattern).test(file))) errors.push(`${feature.file}: path '${pattern}' matches no files`);
    }
  }
  for (const route of routes) if (!claimedRoutes.has(route)) errors.push(`Unmapped route '${route}': add it to routes in the appropriate ${MAP_DIR}/<feature-id>.md`);
  for (const [route, owners] of claimedRoutes) {
    if (!routes.includes(route)) errors.push(`${owners.join(", ")}: route '${route}' matches no Expo Router screen`);
    if (owners.length > 1) errors.push(`Route '${route}' is claimed by multiple features: ${owners.join(", ")}`);
  }
  const pathMatchers = features.flatMap((feature) => feature.paths.map(globRegex));
  const warnings = SOURCE_DIRS.flatMap((dir) => {
    const childDirs = [...new Set(allFiles.filter((file) => file.startsWith(`${dir}/`)).map((file) => file.split("/").slice(0, 2).join("/")))];
    return childDirs.filter((child) => {
      const sourceFiles = allFiles.filter((file) => file.startsWith(`${child}/`) && /\.(?:ts|tsx)$/.test(file));
      return sourceFiles.length >= 3 && !sourceFiles.some((file) => pathMatchers.some((matcher) => matcher.test(file)));
    }).map((child) => `Source area '${child}/' is not covered by any feature paths glob`);
  });
  return { features, routes, errors, warnings, index: renderIndex(features) };
}

export function runFeatureMap(root: string, check: boolean): number {
  const result = inspectFeatureMap(root);
  const indexPath = path.join(root, MAP_DIR, "README.md");
  if (check) {
    const existing = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, "utf8") : "";
    if (existing !== result.index) result.errors.push(`${MAP_DIR}/README.md is stale; run 'npm run feature-map' and stage it`);
  } else if (result.errors.length === 0) {
    fs.writeFileSync(indexPath, result.index);
    console.log(`Updated ${MAP_DIR}/README.md (${result.features.length} features, ${result.routes.length} routes).`);
  }
  for (const warning of result.warnings) console.warn(`feature-map warning: ${warning}`);
  if (result.errors.length > 0) {
    console.error("Feature map validation failed:");
    for (const error of result.errors) console.error(`  - ${error}`);
    console.error(`Fix the matching ${MAP_DIR}/<feature-id>.md, then run 'npm run feature-map'.`);
    return 1;
  }
  if (check) console.log(`Feature map OK: ${result.features.length} features claim ${result.routes.length} user routes.`);
  return 0;
}

if (require.main === module) process.exitCode = runFeatureMap(process.cwd(), process.argv.includes("--check"));
