/**
 * Wire a node:sqlite in-memory DB to getDrizzle() via drizzle sqlite-proxy.
 * Applies alias fix for DISTINCT date(...) generated by Drizzle.
 */
function useDrizzleDb(db: InstanceType<typeof DatabaseSync>) {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const proxyDb = proxyDrizzle(async (sql: string, params: any[], method: string) => {
    // Fix missing alias on DISTINCT date(...) expressions
    const fixedSql = sql.replace(
      /(select\s+DISTINCT\s+date\([^)]+\))(\s+from)/i,
      '$1 AS "d"$2'
    );
    const stmt = db.prepare(fixedSql);
    if (method === "run") {
      stmt.run(...params);
      return { rows: [] };
    }
    if (method === "get") {
      const row = stmt.get(...params) as Record<string, unknown> | undefined;
      return { rows: row ? [Object.values(row)] : [] };
    }
    const rows = stmt.all(...params) as Record<string, unknown>[];
    return { rows: rows.map((r) => Object.values(r)) };
  }, { schema });
  helpers.getDrizzle.mockResolvedValue(proxyDb);
}

